"""Alembic configuration tests.

Every command runs against this test's private database copy (or offline, with
no database). Nothing here generates or applies migrations to a real database.
"""
import io
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text

import app.db.session as app_session
from app.db.base import Base

BACKEND_DIR = Path(__file__).resolve().parents[1]
ALEMBIC_DIR = BACKEND_DIR / "alembic"
VERSIONS_DIR = ALEMBIC_DIR / "versions"


@pytest.fixture(scope="module", autouse=True)
def no_migration_files_created():
    before = sorted(p.name for p in VERSIONS_DIR.iterdir())
    yield
    assert sorted(p.name for p in VERSIONS_DIR.iterdir()) == before, "tests must not create migration files"


def make_config(url: str, monkeypatch) -> Config:
    """Programmatic config (no ini file -> env.py skips logging fileConfig).

    env.py takes its URL from app.db.session.db_url, so point that at `url`.
    """
    monkeypatch.setattr(app_session, "db_url", url)
    cfg = Config(output_buffer=io.StringIO(), stdout=io.StringIO())
    cfg.set_main_option("script_location", str(ALEMBIC_DIR))
    cfg.set_main_option("path_separator", "os")
    return cfg


def test_ini_points_at_alembic_directory():
    script = ScriptDirectory.from_config(Config(str(BACKEND_DIR / "alembic.ini")))
    assert Path(script.dir).resolve() == ALEMBIC_DIR.resolve()
    assert (ALEMBIC_DIR / "env.py").is_file() and VERSIONS_DIR.is_dir()


def test_at_most_one_head():
    script = ScriptDirectory.from_config(Config(str(BACKEND_DIR / "alembic.ini")))
    assert len(script.get_heads()) <= 1, "multiple migration heads - merge them"


def test_current_runs_against_test_db(db_url, monkeypatch):
    command.current(make_config(db_url, monkeypatch))


def test_env_uses_app_db_url_with_percent_escaping(monkeypatch):
    url = "postgresql://user:p%40ss@db.example.invalid/uniinsight"
    cfg = make_config(url, monkeypatch)
    command.upgrade(cfg, "head", sql=True)  # offline: renders SQL, never connects
    assert cfg.get_main_option("sqlalchemy.url") == url


def test_check_finds_no_drift_between_models_and_schema(db_url, monkeypatch):
    command.check(make_config(db_url, monkeypatch))


def test_check_detects_missing_table(db_engine, db_url, monkeypatch):
    """Proves env.py's target_metadata really is the app's model metadata."""
    with db_engine.begin() as conn:
        conn.execute(text("DROP TABLE schedules"))
    with pytest.raises(AutogenerateDiffsDetected, match="schedules"):
        command.check(make_config(db_url, monkeypatch))


def test_upgrade_from_empty_matches_models(tmp_path, monkeypatch):
    script = ScriptDirectory.from_config(Config(str(BACKEND_DIR / "alembic.ini")))
    if not script.get_heads():
        pytest.skip("no migrations yet - create a baseline revision in Phase 1")
    url = f"sqlite:///{(tmp_path / 'empty.db').as_posix()}"
    cfg = make_config(url, monkeypatch)
    command.upgrade(cfg, "head")
    engine = create_engine(url)
    assert set(Base.metadata.tables) <= set(inspect(engine).get_table_names())
    engine.dispose()
    command.check(cfg)
